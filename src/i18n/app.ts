// Preset categories follow the app language; a name the user changed stays as they wrote it.
export function categoryName(category: { name: string; preset: string | null }, locale: Locale): string {
  for (const list of Object.values(CATEGORY_PRESETS)) {
    for (const p of list) {
      if (p.preset === category.preset && (category.name === p.pt || category.name === p.en)) return locale === "en" ? p.en : p.pt;
    }
  }
  return category.name;
}
